"""ORCA's own citation lists, collected from every kept output.

Each ORCA output ends with "SUGGESTED CITATIONS FOR THIS RUN": the papers behind the
algorithms that run used, in four groups (essential, high priority, suggested, optional).
This gathers them over all campaign and study jobs, so the references in the repository
come from ORCA itself, with the methods that needed each one:

    docker compose --profile compute run --rm worker python -m hclust citations > doc/orca-citations.md
"""

import re
from dataclasses import dataclass, field
from pathlib import Path

from sqlmodel import Session, select

from hclust.db import Job, StudyResult
from hclust.levels import LEVELS

GROUPS = {
    "List of essential papers": "essential",
    "List of papers to cite with high priority": "high priority",
    "List of suggested additional citations": "suggested",
    "List of optional additional citations": "optional",
}
ORDER = list(GROUPS.values())
_ENTRY = re.compile(r"^\s{1,4}(\d+)\.\s+(.*\S)\s*$")
TAIL_BYTES = 64 * 1024  # the section sits at the very end of the output


@dataclass(frozen=True)
class Citation:
    authors: str
    title: str
    journal: str
    doi: str | None

    @property
    def key(self) -> str:
        return (self.doi or f"{self.authors} {self.title}").lower()


@dataclass
class Collected:
    citation: Citation
    group: str  # the highest priority any run gave it
    used_by: set[str] = field(default_factory=set)


def parse(text: str) -> list[tuple[str, Citation]]:
    """(group, citation) pairs from the last citation section of an ORCA output."""
    start = text.rfind("SUGGESTED CITATIONS FOR THIS RUN")
    if start < 0:
        return []
    found, group, entry = [], None, None

    def close():
        if entry and group:
            lines = entry
            doi = next((ln.removeprefix("doi.org/") for ln in lines if ln.startswith("doi.org/")), None)
            rest = [ln for ln in lines if not ln.startswith("doi.org/")]
            found.append((group, Citation(rest[0], rest[1] if len(rest) > 1 else "",
                                          " ".join(rest[2:]), doi)))

    for line in text[start:].splitlines():
        header = next((g for prefix, g in GROUPS.items() if line.startswith(prefix)), None)
        if header:
            close()
            group, entry = header, None
            continue
        if group is None:
            continue
        if m := _ENTRY.match(line):
            close()
            entry = [m[2]]
        elif entry is not None and line.strip() and line.startswith("     "):
            entry.append(line.strip())
        elif entry is not None and not line.strip():
            close()
            entry = None
        elif line.strip() and not line.startswith(" "):  # prose or the timings: section over
            if line.startswith("Timings") or "TERMINATED" in line:
                break
    close()
    return found


def _tail(path: Path) -> str:
    with path.open("rb") as f:
        f.seek(max(0, path.stat().st_size - TAIL_BYTES))
        return f.read().decode(errors="replace")


def _label(level: str, task: str) -> str:
    lv = LEVELS.get(level)
    method = f"{lv.method}/{lv.basis}".rstrip("/") if lv else level
    return f"{method} {task}".replace("RI-MP2 RIJK/aug-cc-pVTZ aug-cc-pVTZ/C aug-cc-pVTZ/JK", "RI-MP2/aug-cc-pVTZ")


def collect(session: Session, jobs_root: Path) -> list[Collected]:
    runs: list[tuple[str, str]] = [  # (job hash, what it was)
        (j.hash, _label(j.level, j.task)) for j in session.exec(select(Job)) if j.hash
    ] + [
        (r.hash, f"study: {r.study.split('@')[0]}") for r in session.exec(select(StudyResult)) if r.hash
    ]
    by_key: dict[str, Collected] = {}
    seen: dict[str, str] = {}  # one output per hash
    for job_hash, label in runs:
        if job_hash in seen:
            continue
        out = jobs_root / job_hash / "job.out"
        seen[job_hash] = label
        if not out.is_file():
            continue
        for group, citation in parse(_tail(out)):
            c = by_key.get(citation.key)
            if c is None:
                c = by_key[citation.key] = Collected(citation, group)
            elif ORDER.index(group) < ORDER.index(c.group):
                c.group = group
            c.used_by.add(label)
    return sorted(by_key.values(), key=lambda c: (ORDER.index(c.group), c.citation.authors, c.citation.title))


def render(collected: list[Collected], n_outputs: int | None = None) -> str:
    lines = [
        "# Papers ORCA asks to be cited for this project",
        "",
        "Generated by `python -m hclust citations` from the \"SUGGESTED CITATIONS FOR THIS RUN\"",
        "section of every kept ORCA output (ORCA 6.1.1). ORCA lists the papers behind its own",
        "algorithms; the functionals, basis sets and other tools are in the README.",
        "Each entry keeps the highest priority any run gave it, and the methods that used it.",
        "",
    ]
    for group in ORDER:
        entries = [c for c in collected if c.group == group]
        if not entries:
            continue
        lines += [f"## {group.capitalize()}", ""]
        for c in entries:
            x = c.citation
            doi = f" [doi:{x.doi}](https://doi.org/{x.doi})" if x.doi else ""
            used = ", ".join(sorted(c.used_by))
            lines.append(f"- {x.authors} *{x.title}* {x.journal}.{doi}  \n  Used by: {used}")
        lines.append("")
    return "\n".join(lines)
